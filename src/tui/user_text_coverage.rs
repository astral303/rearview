const SESSION: &str = "7a1b2c3d-4e5f-4a6b-8c7d-8e9f0a1b2c3d";

/// The user texts of the session after its first prompt and reply, in
/// order, each followed by a reply the viewer shows.
const USER_TEXTS: [&str; 9] = [
    "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>",
    "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>",
    "<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>SLASH_ARGS_SENTINEL</command-args>",
    "<command-message>init is analyzing</command-message>\n<command-name>init</command-name>\n<command-args>INIT_ARGS_SENTINEL</command-args>",
    "<local-command-stdout>\u{1b}[2mSTDOUT_SENTINEL printed\u{1b}[22m</local-command-stdout>",
    "<local-command-stderr>STDERR_SENTINEL failed</local-command-stderr>",
    "<local-command-stdout></local-command-stdout>",
    "Base directory for this skill: /home/u/.claude/skills/officecli\n\n# Office CLI\n\nSKILL_BODY_SENTINEL opens the document.",
    "why does <command-name>/model</command-name> show QUOTED_TAG_SENTINEL twice?",
];

/// Queries for text the viewer doesn't show.
const HIDDEN: [&str; 6] = [
    "generated by the user while running local commands",
    "/clear",
    "command-message",
    "command-args",
    "local-command-stdout",
    "skill_body_sentinel",
];

/// Queries for text the viewer shows.
const SHOWN: [&str; 7] = [
    "<command-name>/model</command-name> show",
    "/review slash_args_sentinel",
    "init init_args_sentinel",
    "stdout_sentinel printed",
    "stderr_sentinel failed",
    "skill: officecli",
    "show quoted_tag_sentinel twice",
];

fn record(kind: &str, second: usize, message: Value) -> Value {
    json!({
        "type": kind,
        "timestamp": format!("2026-09-01T10:{:02}:{:02}.000Z", second / 60, second % 60),
        "sessionId": SESSION,
        "cwd": "/tmp/user-texts",
        "message": message,
    })
}

fn write_session(directory: &Path) -> PathBuf {
    let mut records = vec![
        record(
            "user",
            0,
            json!({"role": "user", "content": "Open the notes"}),
        ),
        record(
            "assistant",
            1,
            json!({"id": "msg_0", "role": "assistant", "content": [{"type": "text", "text": "Opened."}]}),
        ),
    ];
    for (index, text) in USER_TEXTS.iter().enumerate() {
        let second = 2 * index + 2;
        records.push(record(
            "user",
            second,
            json!({"role": "user", "content": text}),
        ));
        records.push(record(
            "assistant",
            second + 1,
            json!({"id": format!("msg_{}", index + 1), "role": "assistant",
                "content": [{"type": "text", "text": format!("Reply {}.", index + 1)}]}),
        ));
    }
    let path = directory.join(format!("{SESSION}.jsonl"));
    let lines: Vec<String> = records.iter().map(Value::to_string).collect();
    std::fs::write(&path, lines.join("\n")).unwrap();
    path
}

/// The text each surface reads or shows for the session at `path`.
struct Surfaces {
    fresh_row: Conversation,
    cached_row: Conversation,
    transcript: AgentTranscript,
}

impl Surfaces {
    fn of(path: &Path) -> Self {
        Self {
            fresh_row: list_row(Source::Claude, path, &[]),
            cached_row: cache_session(Source::Claude, path, &[]),
            transcript: AgentTranscript::load_cached_for_test(Source::Claude, path, &[]).unwrap(),
        }
    }

    /// Each surface, true when it matches `query`.
    fn matches(&self, query: &str) -> BTreeMap<&'static str, bool> {
        let literal = Literal::new(query.to_owned());
        let fresh = build_literal_corpus_within(
            std::slice::from_ref(&self.fresh_row),
            &TimeFilter::default(),
        )
        .remove(0)
        .text;
        let cached = SessionSearchTexts::read(self.cached_row.cached_session.as_ref().unwrap())
            .expect("the cache holds the copy");
        let viewer = self.viewer_lines();
        BTreeMap::from([
            ("list search, fresh read", literal.matches(&fresh)),
            ("list search, cached read", literal.matches(cached.joined())),
            (
                "agent search",
                segment_texts(&self.transcript, TimeFilter::default())
                    .iter()
                    .any(|text| literal.matches(text)),
            ),
            (
                "agent read",
                !self.agent_read_messages_matching(&literal).is_empty(),
            ),
            ("viewer /", !find_matches(&viewer, query).is_empty()),
            (
                "exports",
                [
                    ExportFormat::Plain,
                    ExportFormat::Markdown,
                    ExportFormat::Ledger,
                ]
                .into_iter()
                .any(|format| literal.matches(&self.export(format))),
            ),
        ])
    }

    fn agent_read_messages_matching(&self, literal: &Literal) -> BTreeSet<usize> {
        self.transcript
            .messages
            .iter()
            .filter(|message| {
                message
                    .parts
                    .iter()
                    .filter_map(agent_part_text)
                    .any(|text| literal.matches(&text))
            })
            .map(|message| message.ordinal)
            .collect()
    }

    /// The messages whose cached search texts match `literal`.
    fn cached_messages_matching(&self, literal: &Literal) -> BTreeSet<usize> {
        let content = self
            .cached_row
            .load_held_content()
            .expect("the cache holds the copy");
        let row = &content.row;
        (1..=row.message_count)
            .filter(|ordinal| {
                row.texts_of(&[MessageRange::single(*ordinal)])
                    .into_array()
                    .iter()
                    .any(|text| literal.matches(text))
            })
            .collect()
    }

    fn viewer_lines(&self) -> Vec<super::viewer::RenderedLine> {
        let row = &self.cached_row;
        let conversation = current_copy(parse_conversation_file_interactively(
            &InteractiveCache::at(test_cache_base()),
            row.cache_address.as_ref().unwrap(),
            &row.publication,
        ))
        .conversation;
        let options = RenderOptions {
            tool_display: ToolDisplayMode::Full,
            show_thinking: true,
            show_timing: false,
            content_width: 200,
            expanded_tool_outputs: BTreeSet::new(),
            can_expand: false,
            today: TestClock::default().today(),
            zone: TestClock::default().zone(),
        };
        render_parsed_conversation(&conversation, &options).lines
    }

    fn export(&self, format: ExportFormat) -> String {
        let row = &self.cached_row;
        export_content(&row.path, format, ExportOptions::default(), || {
            Ok(current_copy(
                crate::history::display_log_entries_interactively(
                    &InteractiveCache::at(test_cache_base()),
                    row.cache_address.as_ref().unwrap(),
                    &row.publication,
                ),
            ))
        })
        .unwrap()
    }
}

#[test]
fn every_search_reads_user_text_as_viewer_shows_it() {
    let directory = tempfile::tempdir().unwrap();
    let surfaces = Surfaces::of(&write_session(directory.path()));

    let mut differences = Vec::new();
    for (queries, shown) in [(&HIDDEN[..], false), (&SHOWN[..], true)] {
        for query in queries {
            for (surface, matched) in surfaces.matches(query) {
                if matched != shown {
                    differences.push(format!("{query:?}: {surface} matches: {matched}"));
                }
            }
        }
    }
    assert!(
        differences.is_empty(),
        "each surface matches a query for shown text and no query for hidden text:\n{}",
        differences.join("\n")
    );
}

#[test]
fn cached_search_texts_name_shown_text_in_message_agent_read_shows_it_in() {
    let directory = tempfile::tempdir().unwrap();
    let surfaces = Surfaces::of(&write_session(directory.path()));

    for query in SHOWN {
        let literal = Literal::new(query.to_owned());
        let read = surfaces.agent_read_messages_matching(&literal);
        assert_eq!(
            read.len(),
            1,
            "{query:?}: `agent read` shows it in one message"
        );
        assert_eq!(
            surfaces.cached_messages_matching(&literal),
            read,
            "{query:?}: the cached search texts name the message `agent read` shows it in"
        );
    }
}

/// Semantic search reads a user message through its own filter: it keeps a
/// command's arguments and a prompt's words outside a quoted tag.
#[test]
fn semantic_turns_embed_shown_text_filter_keeps_and_no_hidden_text() {
    let directory = tempfile::tempdir().unwrap();
    let row = list_row(Source::Claude, &write_session(directory.path()), &[]);
    let embedded = row.semantic_turns.join("\n");

    for query in HIDDEN {
        assert!(
            !Literal::new(query.to_owned()).matches(&embedded),
            "{query:?}: no semantic turn embeds it: {:?}",
            row.semantic_turns
        );
    }
    for query in ["slash_args_sentinel", "show quoted_tag_sentinel twice"] {
        assert!(
            Literal::new(query.to_owned()).matches(&embedded),
            "{query:?}: a semantic turn embeds it: {:?}",
            row.semantic_turns
        );
    }
}
